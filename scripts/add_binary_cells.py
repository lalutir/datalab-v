            "**[V2] Binary Alert Models -- Interpretation**\n",
            "\n",
            "**AUC-ROC vs persistence**\n",
            "\n",
            "Binary models beat the naive persistence baseline (today's risk >= 2 predicts an alert) at\n",
            "most horizons. The persistence baseline has a structural weakness for the binary target:\n",
            "it only fires when risk is already elevated, missing the many days where conditions are\n",
            "building toward High/Extreme. The XGBoost lag features -- especially API and SPEI lags --\n",
            "capture this pre-escalation signal. This contrasts with the 4-class models in Section 12.2,\n",
            "where no model beat persistence on macro recall.\n",
            "\n",
            "**Threshold at recall = 0.80**\n",
            "\n",
            "For each model, a threshold below 0.50 is typically needed to achieve 80% recall -- the model\n",
            "must be willing to raise many alerts to catch most real events. The precision at this threshold\n",
            "quantifies the false alarm rate: a precision of 0.40 at recall 0.80 means 60% of alerts are\n",
            "false alarms, which may be acceptable for a humanitarian pre-positioning system where the cost\n",
            "of missing a real event outweighs the cost of unnecessary preparation.\n",
            "\n",
            "**4-class vs binary for go/no-go decisions**\n",
            "\n",
            "The binary model is more operationally useful for a single go/no-go alert decision. The 4-class\n",
            "model requires post-hoc thresholding and provides level information that is irrelevant when the\n",
            "decision is binary. In practice, the two are complementary: binary for triggering the alert,\n",
            "4-class for characterising severity after the trigger fires.\n",
            "\n",
            "**EMDAT validation**\n",
